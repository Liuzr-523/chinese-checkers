"""Build the independent extension for the interpreter running this script."""
import os
from pathlib import Path
import shlex
import subprocess
import sys
import sysconfig
import rules121 as r

ROOT = Path(__file__).resolve().parent

def build():
    rows = []
    for q, y in r.COORDS:
        rows.append([r.IDS.get((q+dq, y+dy), -1) for dq, dy in r.DIRECTIONS])
    hops = []
    for q, y in r.COORDS:
        hops.append([r.IDS.get((q+2*dq, y+2*dy), -1) for dq, dy in r.DIRECTIONS])
    def table(name, data):
        return 'static const int '+name+'['+str(len(data))+']['+str(len(data[0]))+'] = {\n'+',\n'.join('{'+','.join(map(str,row))+'}' for row in data)+'\n};\n'
    distances = []
    for q, y in r.COORDS:
        distances.append([max(abs(q-tq), abs(y-ty), abs(q+y-tq-ty))
                          for tq,ty in (r.COORDS[120], r.COORDS[0])])
    (ROOT/'ccore121_tables.h').write_text('/* Generated by build_ccore121.py from rules121. */\n'+table('NEIGHBOR',rows)+table('HOP',hops)+table('DIST',distances))
    output = ROOT/('ccore121'+sysconfig.get_config_var('EXT_SUFFIX'))
    command = shlex.split(os.environ.get('CC', 'clang'))+['-O3','-Wall','-Wextra','-Wno-unused-parameter','-fPIC','-shared', '-I'+sysconfig.get_path('include')]
    if sys.platform == 'darwin': command += ['-undefined','dynamic_lookup']
    subprocess.run(command+[str(ROOT/'ccore121.c'),'-o',str(output)],check=True)
    print(output)

if __name__ == '__main__': build()
